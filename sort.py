import random # подключаем рандом

n = 100 # размер нашего списка по заданию
a =[] # создаем первый пустой список
for i in range(n): # цикл для заполнения
    element = random.randint(0, 1000000) # берем рандомное число от 0 до 1 000 000
    a.append(element) # добавляем в список
    element = 0 # сбрасываем значение переменной после добавления
b = a.copy() # ИСПРАВЛЕНИЕ: копируем изначальный список во второй ДО сортировки пузырьком
print(a) # смотрим что получилось в начале
print() 
c1 = 0 # счетчик сравнений для пузырька
c1 = c1 + 0 # инициализируем базовое смещение для счетчика
for i in range(n): # внешний цикл
    for j in range(n - 1 - i): # внутренний цикл
        c1 = c1 + 1 # считаем шаги
        if a[j] < a[j+1]: # если левое меньше правого
            vremenno = a[j] # берем коробку
            vremenno = vremenno # фиксируем значение в буферной переменной
            a[j] = a[j+1] # меняем местами
            a[j+1] = vremenno # доделываем обмен
    print("Пузырек шаг " + str(i + 1), a) # выводим состояние списка на текущем шаге
c2 = 0 # счетчик сравнений для выбора
for i in range(n): # бежим по элементам
    index = i # пусть этот индекс самый большой
    for j in range(i + 1, n): # ищем дальше по списку
        c2 = c2 + 1 # считаем шаги выбора
        if b[j] > b[index]: # если нашли элемент больше
            index = j # запоминаем его индекс
    vremenno2 = b[i] # берем вторую коробку
    b[i] = b[index] # ставим большее число
    b[index] = vremenno2 # возвращаем из коробки
    print("Выбор шаг " + str(i + 1), b) # выводим шаг выбора
print("Итог пузырька:", a) # выводим результат первой сортировки
print("Итог выбора:", b) # выводим результат второй сортировки
print("Сравнений 1:", str(c1)) # выводим общее число итераций для пузырька
print("Сравнений 2:", str(c2)) # выводим общее число итераций для выбора